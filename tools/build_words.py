#!/usr/bin/env python3
"""Build data/words.js from data-src/wordlist.psv (word|cefr|pos) and
data-src/translations.psv (word|tr1;tr2;tr3|example)."""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
base = {}
for line in (root / "data-src/wordlist.psv").read_text(encoding="utf-8").splitlines():
    w, c, p = line.split("|")
    base[w] = (c, p)

tr = {}
problems = []
for n, line in enumerate((root / "data-src/translations.psv").read_text(encoding="utf-8").splitlines(), 1):
    if not line.strip():
        continue
    parts = line.split("|")
    if len(parts) != 3:
        problems.append(f"line {n}: expected 3 fields: {line[:60]}")
        continue
    w, t, ex = parts
    if w in tr:
        problems.append(f"duplicate word: {w}")
    tr[w] = (t, ex.strip())

# Ek (yaygın) Türkçe karşılıklar: ana çevirilerden sonra eklenir.
extra_path = root / "data-src/extra_translations.psv"
if extra_path.exists():
    for n, line in enumerate(extra_path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        parts = line.split("|")
        if len(parts) != 2 or parts[0] not in tr:
            problems.append(f"extra line {n}: {line[:60]}")
            continue
        w, more = parts
        t, ex = tr[w]
        tr[w] = (t + ";" + ";".join(m for m in more.split(";") if len(m.strip()) > 1 and "(" not in m), ex)

# Örnek cümlelerin Türkçe çevirileri
ex_tr = {}
etp = root / "data-src/example_tr.psv"
if etp.exists():
    for n, line in enumerate(etp.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        w, _, t = line.partition("|")
        if w not in base:
            problems.append(f"example_tr line {n}: unknown word {w}")
        elif w in ex_tr:
            problems.append(f"example_tr duplicate: {w}")
        elif not t.strip():
            problems.append(f"example_tr empty: {w}")
        else:
            ex_tr[w] = t.strip()
    miss_ex = [w for w in base if w not in ex_tr]
    if miss_ex:
        problems.append(f"missing example translations: {miss_ex[:20]} (+{len(miss_ex)})")

missing = [w for w in base if w not in tr]
extra = [w for w in tr if w not in base]
if missing: problems.append(f"missing translations: {missing[:20]} (+{len(missing)})")
if extra: problems.append(f"unknown words: {extra[:20]}")

out = []
for idx, (w, (c, p)) in enumerate(base.items()):
    if w not in tr:
        continue
    t, ex = tr[w]
    seen, meanings = set(), []
    for m in t.split(";"):
        m = m.strip()
        if m and m not in seen:
            seen.add(m)
            meanings.append(m)
    if not meanings:
        problems.append(f"empty translation: {w}")
    out.append([w, c, p, meanings[:4], ex, ex_tr.get(w, "")])

if problems:
    print("\n".join(problems), file=sys.stderr)
    sys.exit(1)

js = "// Generated by tools/build_words.py - do not edit by hand.\n" \
     "// Word list: A1-C1 (Oxford 3000/5000 structure). Fields: word, cefr, pos, tr[], example, exampleTr\n" \
     "window.BLARMA_WORDS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
(root / "data/words.js").write_text(js, encoding="utf-8")
print(f"OK: {len(out)} words, {len(js)//1024} KB")
